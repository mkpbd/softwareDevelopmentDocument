-- FUNCTION: clinical.fn_get_available_slots
-- PURPOSE: Retrieves available doctor slots for a given date range and branch
CREATE OR REPLACE FUNCTION clinical.fn_get_available_slots(
    p_tenant_id UUID,
    p_branch_id UUID,
    p_specialization VARCHAR,
    p_start_date DATE,
    p_end_date DATE
)
RETURNS TABLE (
    slot_id UUID,
    doctor_name VARCHAR,
    slot_start_time TIMESTAMPTZ,
    slot_end_time TIMESTAMPTZ
) AS $$
BEGIN
    RETURN QUERY
    SELECT
        ds.slot_id,
        u.first_name || ' ' || u.last_name AS doctor_name,
        ds.slot_start_time,
        ds.slot_end_time
    FROM
        clinical.doctor_slots ds
    JOIN
        clinical.doctor_schedules sch ON ds.schedule_id = sch.schedule_id
    JOIN
        public.staff s ON sch.staff_id = s.staff_id
    JOIN
        public.users u ON s.user_id = u.user_id
    WHERE
        ds.tenant_id = p_tenant_id
        AND sch.branch_id = p_branch_id
        AND s.specialization = p_specialization
        AND ds.slot_status = 1 -- Available
        AND ds.slot_start_time >= p_start_date::TIMESTAMPTZ
        AND ds.slot_start_time < (p_end_date + INTERVAL '1 day')::TIMESTAMPTZ
    ORDER BY
        ds.slot_start_time ASC;
END;
$$ LANGUAGE plpgsql SECURITY INVOKER;

-- STORED PROCEDURE: clinical.sp_book_appointment
-- PURPOSE: Books an appointment, updating the slot status transactionally
CREATE OR REPLACE PROCEDURE clinical.sp_book_appointment(
    p_tenant_id UUID,
    p_patient_id UUID,
    p_slot_id UUID,
    p_reason_for_visit TEXT,
    OUT p_appointment_id UUID
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_slot_status SMALLINT;
    v_schedule_id UUID;
    v_staff_id UUID;
    v_branch_id UUID;
    v_slot_start TIMESTAMPTZ;
    v_slot_end TIMESTAMPTZ;
    v_slot_type SMALLINT;
BEGIN
    -- 1. Lock the slot row to prevent concurrent bookings
    SELECT slot_status, schedule_id, slot_start_time, slot_end_time, slot_type
    INTO v_slot_status, v_schedule_id, v_slot_start, v_slot_end, v_slot_type
    FROM clinical.doctor_slots
    WHERE slot_id = p_slot_id AND tenant_id = p_tenant_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Slot not found.';
    END IF;

    IF v_slot_status != 1 THEN -- 1 = Available
        RAISE EXCEPTION 'Slot is no longer available.';
    END IF;

    -- 2. Get schedule details
    SELECT staff_id, branch_id
    INTO v_staff_id, v_branch_id
    FROM clinical.doctor_schedules
    WHERE schedule_id = v_schedule_id;

    -- 3. Create the appointment
    INSERT INTO clinical.appointments (
        tenant_id, patient_id, doctor_staff_id, branch_id, slot_id,
        appointment_date, appointment_start_time, appointment_end_time,
        appointment_type, appointment_status, reason_for_visit
    ) VALUES (
        p_tenant_id, p_patient_id, v_staff_id, v_branch_id, p_slot_id,
        v_slot_start::DATE, v_slot_start, v_slot_end,
        v_slot_type, 1, p_reason_for_visit -- 1 = Scheduled
    ) RETURNING appointment_id INTO p_appointment_id;

    -- 4. Update the slot status
    UPDATE clinical.doctor_slots
    SET slot_status = 2, -- 2 = Booked
        patient_id = p_patient_id,
        appointment_id = p_appointment_id,
        updated_at = NOW()
    WHERE slot_id = p_slot_id;

    -- Transaction commits automatically at the end of the procedure
END;
$$;

