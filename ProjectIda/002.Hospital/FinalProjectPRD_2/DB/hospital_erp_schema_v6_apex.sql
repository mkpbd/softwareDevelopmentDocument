-- FUNCTION: audit.fn_audit_trigger()
-- PURPOSE: Generic trigger function to capture changes and log them to audit.audit_logs
CREATE OR REPLACE FUNCTION audit.fn_audit_trigger()
RETURNS TRIGGER AS $$
DECLARE
    v_tenant_id UUID;
    v_user_id UUID;
    v_old_data JSONB;
    v_new_data JSONB;
    v_record_id VARCHAR(255);
BEGIN
    -- Attempt to get tenant_id and user_id from session context
    BEGIN
        v_tenant_id := current_setting('app.tenant_id')::UUID;
    EXCEPTION WHEN OTHERS THEN
        v_tenant_id := NULL; -- Fallback if not set
    END;

    BEGIN
        v_user_id := current_setting('app.user_id')::UUID;
    EXCEPTION WHEN OTHERS THEN
        v_user_id := NULL; -- Fallback if not set
    END;

    IF TG_OP = 'INSERT' THEN
        v_new_data := row_to_json(NEW);
        -- Assuming the first column is the primary key for simplicity in this generic trigger
        -- In a real scenario, you might need a more robust way to identify the PK
        EXECUTE format('SELECT ($1).%I', (SELECT a.attname FROM pg_index i JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey) WHERE i.indrelid = TG_RELID AND i.indisprimary)) USING NEW INTO v_record_id;
        
        INSERT INTO audit.audit_logs (tenant_id, user_id, action_date, action_type, table_name, record_id, new_data)
        VALUES (COALESCE(v_tenant_id, NEW.tenant_id), v_user_id, CURRENT_DATE, TG_OP, TG_TABLE_NAME, v_record_id, v_new_data);
        RETURN NEW;
    ELSIF TG_OP = 'UPDATE' THEN
        v_old_data := row_to_json(OLD);
        v_new_data := row_to_json(NEW);
        EXECUTE format('SELECT ($1).%I', (SELECT a.attname FROM pg_index i JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey) WHERE i.indrelid = TG_RELID AND i.indisprimary)) USING NEW INTO v_record_id;

        INSERT INTO audit.audit_logs (tenant_id, user_id, action_date, action_type, table_name, record_id, old_data, new_data)
        VALUES (COALESCE(v_tenant_id, NEW.tenant_id), v_user_id, CURRENT_DATE, TG_OP, TG_TABLE_NAME, v_record_id, v_old_data, v_new_data);
        RETURN NEW;
    ELSIF TG_OP = 'DELETE' THEN
        v_old_data := row_to_json(OLD);
        EXECUTE format('SELECT ($1).%I', (SELECT a.attname FROM pg_index i JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = ANY(i.indkey) WHERE i.indrelid = TG_RELID AND i.indisprimary)) USING OLD INTO v_record_id;

        INSERT INTO audit.audit_logs (tenant_id, user_id, action_date, action_type, table_name, record_id, old_data)
        VALUES (COALESCE(v_tenant_id, OLD.tenant_id), v_user_id, CURRENT_DATE, TG_OP, TG_TABLE_NAME, v_record_id, v_old_data);
        RETURN OLD;
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

